export function getClubBadgeUrl(clubName: string): string | null {
  if (!clubName) return null;
  const clean = clubName.toLowerCase().replace(/['']/g, '').trim();
  if (clubBadgesMap[clean]) {
    return clubBadgesMap[clean];
  }
  // Partial matches
  for (const [key, url] of Object.entries(clubBadgesMap)) {
    if (clean.includes(key) || key.includes(clean)) {
      return url;
    }
  }
  return null;
}
